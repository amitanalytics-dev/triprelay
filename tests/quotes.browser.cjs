const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const http = require('node:http');
(async () => {
  fs.mkdirSync('tmp/quote-ui', {recursive:true});
  fs.mkdirSync('tmp/quote-browser', {recursive:true});
  await esbuild.build({ entryPoints:['tests/quote-ui.entry.tsx'], outfile:'tmp/quote-ui/screen.js', bundle:true,
    platform:'browser', format:'iife', jsx:'automatic', alias:{'convex/react':path.resolve('tests/quote-ui.fixtures.ts')},
    define:{'process.env.NODE_ENV':'"development"'} });
  fs.writeFileSync('tmp/quote-ui/index.html','<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="screen.css"></head><body><div id="root"></div><script src="screen.js"></script></body></html>');
  const server=http.createServer((request,response)=>{
    const pathname=new URL(request.url,'http://127.0.0.1').pathname;
    const file=pathname==='/'?'index.html':pathname.slice(1);
    if(!['index.html','screen.js','screen.css'].includes(file)){response.writeHead(404).end();return;}
    response.setHeader('Content-Type',file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':'text/html');
    response.end(fs.readFileSync(path.join('tmp/quote-ui',file)));
  });
  await new Promise(resolve=>server.listen(5181,'127.0.0.1',resolve));
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844}});
  page.on('pageerror', error => console.log('Test-screen error: '+error.message));
  try {
    const base='http://127.0.0.1:5181/?scenario=';
    await page.goto(base+'approved'); await page.getByRole('article',{name:'Approved quote'}).waitFor();
    assert.equal(await page.getByText('SYNTHETIC-PRIVATE-REFERENCE').count(),0);
    assert.equal(await page.getByText('Permitted minimum client price').count(),0);
    assert.equal(await page.getByText('SAMPLE private client limit:',{exact:false}).count(),0);
    await page.getByText('Final client total · GST included').waitFor();
    assert.equal(await page.getByRole('button',{name:'Download branded PDF'}).isVisible(),true);
    const downloaded = page.waitForEvent('download');
    await page.getByRole('button',{name:'Download branded PDF'}).click();
    const file = await downloaded;
    await file.saveAs('tmp/quote-browser/sample-reviewed-quote.pdf');
    assert.equal(fs.readFileSync('tmp/quote-browser/sample-reviewed-quote.pdf').subarray(0,5).toString(),'%PDF-');
    await page.goto(base+'download-failure');
    await page.getByRole('button',{name:'Download branded PDF'}).click();
    await page.getByRole('alert').filter({hasText:'Sample PDF preparation failed'}).waitFor();
    await page.goto(base+'logo-webp');
    const logoDownload=page.waitForEvent('download');
    await page.getByRole('button',{name:'Download branded PDF'}).click();
    await (await logoDownload).saveAs('tmp/quote-browser/sample-logo-quote.pdf');
    assert.equal(await page.evaluate(()=>window.testLogoConverted),true);
    await page.goto(base+'approved');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:'tmp/quote-browser/approved-sample-mobile.png',fullPage:true});
    await page.goto(base+'expiry'); await page.getByRole('article',{name:'Approved quote'}).waitFor();
    await page.getByText('This quote is not ready for clients.').waitFor();
    assert.equal(await page.getByRole('article',{name:'Approved quote'}).count(),0);
    await page.goto(base+'review-blocked'); await page.getByText('Approval is blocked.').waitFor();
    assert.equal(await page.getByRole('button',{name:'Approve this version'}).isDisabled(),true);
    await page.goto(base+'review-ready'); await page.getByRole('button',{name:'Approve this version'}).click();
    await page.getByText('SAMPLE private client limit:',{exact:false}).waitFor();
    await page.getByText('Fresh matching terms are missing.').waitFor();
    assert.equal(await page.getByText('Not a verified quote.').isVisible(),true);
    await page.getByRole('button',{name:'Next hotel checks'}).click();
    await page.getByText('2026-11-10 to 2026-11-11 · Da Nang · 5-star',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Previous hotel checks'}).click();
    await page.getByText('2026-11-09 to 2026-11-10 · Hanoi · 4-star',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.getByText('Permitted minimum client price').waitFor();
    await page.getByText('This quote version is approved.').waitFor();
    assert.equal(await page.evaluate(()=>window.testDecision.decision),'approved');
    await page.getByLabel('Review note').fill('Sample correction reason');
    await page.getByRole('button',{name:'Request corrections'}).click();
    await page.getByText('This version needs corrections. Earlier approval cannot release it.').waitFor();
    assert.equal(await page.evaluate(()=>window.testDecision.decision),'rejected');
    await page.screenshot({path:'tmp/quote-browser/reviewer-sample-mobile.png',fullPage:true});
    await page.goto(base+'review-lowest');
    await page.getByRole('heading',{name:'Compared alternatives (2)'}).waitFor();
    await page.getByText('Every compared choice remains fresh and reviewed.').waitFor();
    assert.equal(await page.getByRole('region',{name:'Reviewed price comparison'}).getByRole('listitem').count(),2);
    assert.equal(await page.getByRole('button',{name:'Approve this version'}).isEnabled(),true);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    await page.screenshot({path:'tmp/quote-browser/reviewer-comparison-sample-mobile.png',fullPage:true});
    await page.goto(base+'review-source-stale');
    await page.getByText('The current brief has changed; prepare a new version.').waitFor();
    assert.equal(await page.getByRole('button',{name:'Approve this version'}).isDisabled(),true);
    await page.getByLabel('Saved enquiries (latest 20)').selectOption('other-intake');
    await page.getByText('SAMPLE second enquiry: dates still unknown.').waitFor();
    await page.getByText('Hotel searches have not been prepared.').waitFor();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.goto(base+'review-source-loading');
    await page.getByText('Loading the original enquiry for this version…').waitFor();
    assert.equal(await page.getByRole('button',{name:'Approve this version'}).isDisabled(),true);
    console.log('PASS: sample PDF and review flow, original/corrected enquiry, safe failed-step display, check paging and selection, pending/stale source approval blocks, private-data exclusion and 390px layout. Supplier/query/mutation data simulated; no real quote/approval created.');
  } finally {await browser.close(); await new Promise(resolve=>server.close(resolve));}
})().catch(error=>{console.error(error.name+': '+error.message);process.exitCode=1;});
